const calculateDistance = (
  lat1,
  lon1,
  lat2,
  lon2
) => {
  const radius = 6371;

  const dLat =
    ((lat2 - lat1) *
      Math.PI) /
    180;

  const dLon =
    ((lon2 - lon1) *
      Math.PI) /
    180;

  const a =
    Math.sin(
      dLat / 2
    ) ** 2 +
    Math.cos(
      (lat1 * Math.PI) /
        180
    ) *
      Math.cos(
        (lat2 * Math.PI) /
          180
      ) *
      Math.sin(
        dLon / 2
      ) ** 2;

  const c =
    2 *
    Math.atan2(
      Math.sqrt(a),
      Math.sqrt(
        1 - a
      )
    );

  return radius * c;
};

const detectCityFromAddress = (
  location = ""
) => {
  const text =
    location
      .toLowerCase()
      .trim();

  if (!text) {
    return null;
  }

  const cityNames =
    Object.keys(
      CITY_ALIASES
    );

  for (
    const cityName of cityNames
  ) {
    const aliases =
      CITY_ALIASES[
        cityName
      ];

    const found =
      aliases.some(
        (alias) =>
          text.includes(
            alias
          )
      );

    if (found) {
      return cityName;
    }
  }

  return null;
};

const findNearestSupportedCity = (
  latitude,
  longitude
) => {
  const cities =
    Object.entries(
      CITY_DEPARTMENTS
    );

  const citiesWithDistance =
    cities.map(
      ([
        cityName,
        cityData,
      ]) => ({
        cityName,

        distance:
          calculateDistance(
            latitude,
            longitude,
            cityData.center
              .latitude,
            cityData.center
              .longitude
          ),
      })
    );

  citiesWithDistance.sort(
    (a, b) =>
      a.distance -
      b.distance
  );

  return (
    citiesWithDistance[0]
      ?.cityName ||
    null
  );
};

export const findNearestDepartment =
  ({
    latitude,
    longitude,
    category,
    location = "",
  }) => {
    const lat =
      Number(latitude);

    const lng =
      Number(longitude);

    if (
      !Number.isFinite(
        lat
      ) ||
      !Number.isFinite(
        lng
      )
    ) {
      return null;
    }

    let city =
      detectCityFromAddress(
        location
      );

    if (!city) {
      city =
        findNearestSupportedCity(
          lat,
          lng
        );
    }

    if (
      !city ||
      !CITY_DEPARTMENTS[
        city
      ]
    ) {
      return null;
    }

    const cityData =
      CITY_DEPARTMENTS[
        city
      ];

    let candidates =
      cityData.departments.filter(
        (department) =>
          department.category ===
          category
      );

    if (
      candidates.length === 0
    ) {
      candidates =
        cityData.departments.filter(
          (department) =>
            department.category ===
            "Other"
        );
    }

    if (
      candidates.length === 0
    ) {
      candidates =
        cityData.departments;
    }

    const withDistance =
      candidates.map(
        (department) => ({
          ...department,

          city,

          distance:
            calculateDistance(
              lat,
              lng,
              department.latitude,
              department.longitude
            ),
        })
      );

    withDistance.sort(
      (a, b) =>
        a.distance -
        b.distance
    );

    return (
      withDistance[0] ||
      null
    );
  };

